/**
 * Generates packages/db/migrations/0002_auth.sql from the Better Auth configuration, so the
 * auth tables are reviewed and versioned like every other migration (Stage 2 §11.1).
 * Run with: node scripts/generate-auth-migration.ts
 * Re-run only when the auth configuration or Better Auth version changes, and review the diff.
 */
import { writeFile, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import pg from 'pg';
import { getMigrations } from 'better-auth/db/migration';
import { createAuth } from '../packages/api/src/auth.ts';
import { startTestDatabase } from '../packages/db/src/test-database.ts';

const target = fileURLToPath(new URL('../packages/db/migrations/0002_auth.sql', import.meta.url));
await rm(target, { force: true });

const database = await startTestDatabase();
try {
  await database.pool.query('CREATE SCHEMA IF NOT EXISTS auth');
  const authPool = new pg.Pool({ ...database.connection, options: '-c search_path=auth' });
  const auth = createAuth({
    pool: authPool,
    baseURL: 'http://localhost:3000',
    secret: 'generation-only-secret-not-used-at-runtime-000',
    sendEmail: async () => undefined,
    checkBreachedPasswords: false,
    secureCookies: false,
  });
  const { compileMigrations } = await getMigrations(auth.options);
  const sql = await compileMigrations();
  await authPool.end();

  const header = `-- 0002 · Authentication tables (Better Auth 1.7.11), generated by scripts/generate-auth-migration.ts.
-- Lives in its own schema. The application's financial role (fin_app) has no access to it.
-- Review the diff whenever this file is regenerated.

CREATE SCHEMA IF NOT EXISTS auth;
SET LOCAL search_path = auth;

`;
  const footer = `

DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'auth_app') THEN
    CREATE ROLE auth_app NOLOGIN;
  END IF;
END
$$;
GRANT USAGE ON SCHEMA auth TO auth_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA auth TO auth_app;
REVOKE ALL ON SCHEMA auth FROM fin_app;
`;
  await writeFile(target, header + sql.trim() + footer, 'utf8');
  console.log(`Wrote ${target}`);
} finally {
  await database.stop();
}
